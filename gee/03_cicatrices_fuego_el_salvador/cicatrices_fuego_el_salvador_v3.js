// Landsat 8 / 9 Collection 2 L2 — una sola función para ambos sensores.
// Se filtra por el área de estudio (no por path/row): Chalatenango está en paths 18–19 y rows 50–51.
function landsat(ids, startDate, endDate) {
  var col = ee.ImageCollection(ids[0]);
  for (var i = 1; i < ids.length; i++) { col = col.merge(ee.ImageCollection(ids[i])); }
  col = col.filterBounds(aoi).filterDate(startDate, endDate);
  print('Imágenes Landsat en el período:', col.size());
  return col
    .map(function(img) {
      var qa = img.select('QA_PIXEL');
      // Bits 1 (nube dilatada), 2 (cirros), 3 (sombra de nube) y 4 (nube)
      var mask = qa.bitwiseAnd(parseInt('11110', 2)).eq(0);
      return img.updateMask(mask);
    })
    .select(['SR_B2', 'SR_B3', 'SR_B4', 'SR_B5', 'SR_B6', 'SR_B7'],
            ['B_1', 'B_2', 'B_3', 'B_4', 'B_5', 'B_7'])
    .map(function(img) {
      return img.multiply(0.0000275).add(-0.2).multiply(10000);
    })
    .median()
    .toUint16()
    .clip(aoi);
}

